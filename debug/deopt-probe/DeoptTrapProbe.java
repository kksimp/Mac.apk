    private static void warmUp(long ms) {
        long end = System.nanoTime() + ms * 1_000_000L;
        do {
            // Both ways of the recursion, so that neither is an uncommon trap later.
            for (int i = 0; i < 700; i++) sink += rec(2);
        } while (System.nanoTime() < end);
    }

    /** The ms since the agent started, like the JVM's own logs have. */
    private static long ms() {
        return (System.nanoTime() - T0) / 1_000_000;
    }

    private static void say(String what) {
        System.err.println("[deopt-probe] [" + ms() + " ms] " + what);
    }

    private static void run(int delayMs, int depth) {
        try {
            try (InputStream in = DeoptTrapProbe.class.getResourceAsStream("Sub.class")) {
                subClass = in.readAllBytes();
            }
            Thread.sleep(delayMs);
            say("warming up");
            warmUp(1500);
            Thread.sleep(500);                       // let the compiler finish with it
            byte[] a = new byte[64 << 20], b = new byte[64 << 20];
            from = a;
            to = b;
            go = false;                              // the warm-up raised it
            Thread loader = new Thread(null, () -> {
                while (!go) {                        // spin: the trigger must not be late
                    Thread.onSpinWait();
                }
                long t0 = System.nanoTime();
                try {
                    // Defining the class is what deoptimizes rec: Leaf stops having no subclasses.
                    Class<?> c = MethodHandles.lookup().defineClass(subClass);
                    sink += c.getModifiers();
                } catch (Throwable t) {
                    throw new RuntimeException(t);
                } finally {
                    say("loader: go seen at " + (t0 - T0) / 1_000_000 + " ms, defineClass took "
                        + (System.nanoTime() - t0) / 1_000_000 + " ms");
                }
            }, "deopt-probe-loader");
            loader.setDaemon(true);
            loader.start();
            say(depth + " frames going on the stack; the loader thread defines the class"
                + " while the innermost one copies");
            long t0 = System.nanoTime();
            sink += rec(depth);
            say("unwound " + depth + " frames: still alive, sink=" + sink
                + ", " + (System.nanoTime() - t0) / 1_000_000 + " ms in them");
            Thread.sleep(300);
            Runtime.getRuntime().halt(0);
        } catch (Throwable t) {
            t.printStackTrace();
            Runtime.getRuntime().halt(3);
        }
    }

    public static void premain(String args, Instrumentation inst) {
        int delayMs = 12000;
        int depth = 8;
        if (args != null && !args.isEmpty()) {
            String[] a = args.split(",");
            delayMs = Integer.parseInt(a[0]);
            if (a.length > 1) depth = Integer.parseInt(a[1]);
        }
        say("loaded (delay " + delayMs + " ms, depth " + depth + ")");
        final int delay = delayMs, frames = depth;
        Thread t = new Thread(null, () -> run(delay, frames), "deopt-probe");
        t.setDaemon(true);
        t.start();
    }
