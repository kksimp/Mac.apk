/**
 * Puts the runtime's SIGILL handler in the situation that used to kill the process: a
 * compiled, recursive method is deoptimized while frames of it are on one thread's stack,
 * and that thread then unwinds. Every frame that returns into the recursive call traps
 * at the same pc.
 *
 * A javaagent. premain starts one thread ("deopt-probe"), which waits (the app boots,
 * the runtime installs its SIGILL handler in front of the JVM's own), runs the scenario
 * and halts the VM. Arguments: delay in ms (default 12000), recursion depth (default 8).
 * Run it with debug/check_sigill_serviced_deopt_traps.sh.
 *
 * How the scenario comes about:
 *
 *  - rec is compiled, and its code relies on Leaf having no subclasses: the cast in it is
 *    compiled as a check for exactly Leaf. Defining Sub, which extends Leaf, ends that,
 *    and HotSpot deoptimizes rec. With frames of rec on stacks it does so lazily: the
 *    compiled code is made not entrant, and the nop after every call in it is replaced
 *    by a trap instruction (0xd4ade001). The JVM's SIGILL handler answers that trap by
 *    sending the frame to the deopt code.
 *
 *  - Lazy, because HotSpot also asks every thread to deoptimize such frames itself (a
 *    handshake), and a thread does that when it next returns from a runtime call, takes
 *    a branch in interpreted code, or polls in compiled code -- at every return in
 *    compiled code -- all of its frames at once, without a trap. For the traps to happen
 *    the thread must come back into the patched calls before it does any of that:
 *
 *      * The innermost frame of rec spends a while in array copies, straight-line code
 *        in the compiled rec: no loop, no call to return from, so no poll. (That is why
 *        the copies are written out one by one.) While it does, the other thread defines
 *        the class. Then it calls wait, and wait returns into the trap after that call:
 *        the first trap. It deoptimizes the innermost frame. (wait is interpreted for
 *        good: a compiled wait would poll at its return first, and attend to the
 *        handshake.)
 *      * An interpreted frame does not poll on return. The innermost frame, interpreted
 *        now, returns at once into the frame below it -- into the trap there: the return
 *        address it saved is the trap instruction, whatever the handshake would do to
 *        the frames below. Each frame of the recursion answers the same trap on its way
 *        out.
 *
 *  - The trigger comes from another thread: the thread that requests a handshake waits
 *    for it.
 */
