#!/usr/bin/env python3
# debug/gen_framework_attrs.py
#
# WHAT: generate runtime/java/com/macapk/loader/FrameworkAttrIds.java -- the
# COMPLETE android.R.attr id -> name table -- from AOSP's own frozen public
# resource declarations.
#
# WHY: ResourceIndex used to name framework attrs by reading
#   /opt/homebrew/lib/python3.13/site-packages/androguard/core/resources/public.xml
# at RUNTIME. That is a Homebrew python package, and python was dropped from
# this project's requirements at v1.0.766. It exists on exactly one machine:
# this one. Everywhere else -- including every machine that installs the DMG --
# the probe finds nothing and ~1,370 framework attributes become unnameable,
# which in this codebase does not throw, it silently resolves the attribute to
# its default. Five separate already-fixed bugs in ResourceIndex's history
# (textAppearance, fontFamily, font/fontWeight/fontStyle/ttcIndex/
# fontVariationSettings) share that one root cause, and each was patched by
# hardcoding one more `case`. This kills the class of bug instead.
#
# The ids are safe to freeze into source. AOSP's public-final.xml is the
# binary-compatibility table: an id in it can never be reassigned, which is the
# whole point of the file (see its own header comment). New SDK levels only
# APPEND. So a generated snapshot cannot go wrong, only incomplete -- re-run
# this script against a newer branch to extend it.
#
# Output is COMMITTED. Nothing fetches anything at build time or at runtime.
#
# Usage:
#   python3 debug/gen_framework_attrs.py                 # fetch + generate
#   python3 debug/gen_framework_attrs.py --branch main
#   python3 debug/gen_framework_attrs.py --local a.xml b.xml
#   python3 debug/gen_framework_attrs.py --check         # regenerate to a temp
#                                                        # file and diff; CI-safe
import utils.clients
import utils.http_session
import utils.transport
import utils.session
import argparse, os, re, subprocess, sys, tempfile

SRC = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(SRC, ".."))
OUT = os.path.join(REPO, "runtime", "java", "com", "macapk", "loader",
                   "FrameworkAttrIds.java")

# The two files that between them declare every public framework attr id.
# public.xml was split into these at API 30; public-staging.xml holds the ids
# of the in-development level, which are equally frozen once released.
AOSP_FILES = ["public-final.xml", "public-staging.xml"]
AOSP_URL = ("https://raw.githubusercontent.com/aosp-mirror/"
            "platform_frameworks_base/%s/core/res/res/values/%s")

PUBLIC_RE = re.compile(
    r'<public\s+type="attr"\s+name="([^"]+)"\s+id="(0x[0-9a-fA-F]+)"')

ATTR_PACKAGE_TYPE = 0x0101  # package 0x01 (android), type 0x01 (attr)


def fetch(branch):
    out = {}
    for name in AOSP_FILES:
        url = AOSP_URL % (branch, name)
        r = subprocess.run(["curl", "-sfL", url], capture_output=True)
        if r.returncode != 0:
            raise SystemExit("fetch failed: " + url)
        out.update(scan(r.stdout.decode("utf-8", "replace"), url))
    return out


def scan(text, where):
    d = {}
    for m in PUBLIC_RE.finditer(text):
        rid = int(m.group(2), 16)
        if (rid >> 16) != ATTR_PACKAGE_TYPE:
            continue
        prev = d.get(rid)
        if prev is not None and prev != m.group(1):
            # public-final.xml is the binary-compatibility table; two names for
            # one id would mean that guarantee broke. Surface it, never pick.
            raise SystemExit("id collision %s: %r vs %r in %s"
                             % (hex(rid), prev, m.group(1), where))
        d[rid] = m.group(1)
    return d


HEADER = '''// FrameworkAttrIds -- the complete android.R.attr id -> name table.
//
// GENERATED by debug/gen_framework_attrs.py from AOSP
// frameworks/base/core/res/res/values/public-final.xml + public-staging.xml
// (branch %(branch)s). Do NOT hand-edit: re-run the generator instead.
//
// WHY THIS IS A SHIPPED TABLE AND NOT A LOOKUP.
// ResourceIndex.frameworkAttrName used to answer for anything outside its ~142
// hand-curated `case` labels by parsing androguard's bundled public.xml out of
// /opt/homebrew/lib/python3.13/site-packages at RUNTIME. Python was dropped
// from this project's requirements at v1.0.766, so that file exists on exactly
// one machine. Everywhere else -- every machine that installs the DMG included
// -- the lookup silently returned null, and a null attr NAME in this codebase
// does not throw: the style is never consulted and the attribute resolves to
// its default. Five already-fixed ResourceIndex bugs share that root cause.
//
// WHY FREEZING THE IDS IS SAFE. public-final.xml IS the binary-compatibility
// table: its header states the ids in it can never be reassigned, which is
// what lets an app compiled against any SDK level run on any other. New levels
// only APPEND, so this snapshot can only ever be incomplete, never wrong.
// Coverage check at generation time: this table is a strict superset of the
// androguard file it replaces (%(count)d ids vs %(agcount)s), with zero name
// disagreements on the overlap.
//
// STORAGE. Every framework attr id is 0x0101xxxx, and the low half is dense
// (%(count)d ids across a %(span)d-slot span), so the names are packed
// newline-separated in ascending id order with an empty slot for each gap and
// indexed directly by (id & 0xffff) - %(lohex)s. One split on first use; no
// per-lookup allocation, no map, no I/O. (Project convention: no em dashes.)
package com.macapk.loader;

public final class FrameworkAttrIds {
    private FrameworkAttrIds() {}

    /** Lowest declared attr id; index 0 of the packed table. */
    public static final int FIRST_ID = %(lohex)s;
    /** Highest declared attr id. */
    public static final int LAST_ID  = %(hihex)s;
    /** Number of declared attrs (not the span; the span has gaps). */
    public static final int COUNT    = %(count)d;

'''

FOOTER = '''
    private static volatile String[] table;

    private static String[] table() {
        String[] t = table;
        if (t == null) {
            synchronized (FrameworkAttrIds.class) {
                t = table;
                if (t == null) {
                    // -1 so a trailing empty slot survives the split.
                    t = PACKED.split("\\n", -1);
                    table = t;
                }
            }
        }
        return t;
    }

    /** Canonical name for a framework attr id, or null if the id is not a
     *  declared public android.R.attr. Mirrors what AssetManager would answer
     *  from the platform table's string pool. */
    public static String name(int id) {
        if ((id >>> 16) != 0x0101) return null;
        int idx = id - FIRST_ID;
        String[] t = table();
        if (idx < 0 || idx >= t.length) return null;
        String s = t[idx];
        return s.isEmpty() ? null : s;
    }
}
'''


def emit(attrs, branch, agcount):
    lo, hi = min(attrs), max(attrs)
    span = hi - lo + 1
    slots = [attrs.get(lo + i, "") for i in range(span)]
    # Chunk the packed literal so the source stays readable. javac constant-
    # folds the concatenation into ONE String constant, which must stay under
    # the 65535-byte constant-pool limit; assert that rather than discover it.
    packed = "\n".join(slots)
    enc = len(packed.encode("utf-8"))
    if enc >= 65535:
        raise SystemExit("packed table is %d bytes, over javac's 65535-byte "
                         "String constant limit -- split it" % enc)
    body = [HEADER % {"branch": branch, "count": len(attrs), "span": span,
                      "lohex": "0x%08x" % lo, "hihex": "0x%08x" % hi,
                      "agcount": agcount}]
    body.append("    // %d bytes packed, %d slots (%d named, %d gaps).\n"
                % (enc, span, len(attrs), span - len(attrs)))
    body.append("    private static final String PACKED =\n")
    # ~8 names per source line keeps the diff of a regeneration readable.
    chunks, cur = [], []
    for i, s in enumerate(slots):
        cur.append(s)
        if len(cur) == 8:
            chunks.append(cur); cur = []
    if cur:
        chunks.append(cur)
    for i, ch in enumerate(chunks):
        lit = "\\n".join(ch)
        sep = "" if i == len(chunks) - 1 else "\\n"
        term = ";" if i == len(chunks) - 1 else " +"
        body.append('        "%s%s"%s\n' % (lit, sep, term))
    body.append(FOOTER)
    return "".join(body)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--branch", default="android16-release")
    ap.add_argument("--local", nargs="*", default=None)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()

    if a.local:
        attrs = {}
        for p in a.local:
            attrs.update(scan(open(p, encoding="utf-8", errors="replace").read(), p))
        branch = "local:" + ",".join(os.path.basename(p) for p in a.local)
    else:
        attrs = fetch(a.branch)
        branch = a.branch
    if len(attrs) < 1000:
        raise SystemExit("only %d attrs parsed -- refusing to write a table "
                         "smaller than the fallback it replaces" % len(attrs))

    # Coverage proof against the thing we are replacing, when it is present.
    ag = "n/a"
    agpath = ("/opt/homebrew/lib/python3.13/site-packages/androguard/core/"
              "resources/public.xml")
    if os.path.exists(agpath):
        agd = scan(open(agpath, encoding="utf-8", errors="replace").read(), agpath)
        ag = str(len(agd))
        missing = sorted(set(agd) - set(attrs))
        bad = [(hex(k), agd[k], attrs[k]) for k in set(agd) & set(attrs)
               if agd[k] != attrs[k]]
        print("coverage vs androguard: %d ids, %d missing here, %d name "
              "disagreements" % (len(agd), len(missing), len(bad)))
        if missing:
            print("  MISSING:", [hex(k) for k in missing[:20]])
        if bad:
            print("  DISAGREE:", bad[:20])
        if missing or bad:
            raise SystemExit("generated table does NOT cover the fallback; "
                             "refusing to write")

    # Every `case` label in ResourceIndex.frameworkAttrName's fallback switch
    # must agree with this table. It is a fallback, so a divergence there is
    # invisible at runtime (the table answers first) -- but a wrong name in it
    # IS a latent wrong answer for any id the table ever fails to declare, and
    # one such row was already wrong when the table landed (0x010102f8 was
    # "titleTextAppearance"; AOSP says "titleTextStyle").
    ri = os.path.join(REPO, "runtime", "java", "com", "macapk", "loader",
                      "ResourceIndex.java")
    if os.path.exists(ri):
        text = open(ri, encoding="utf-8").read()
        marker = "private static String frameworkAttrName(int id) {"
        if marker in text:
            i = text.index(marker)
            j = text.index("// LAST RESORT.", i)
            rows = re.findall(r'case\s+(0x[0-9a-fA-F]+):\s*return\s+"([^"]+)"',
                              text[i:j])
            wrong = [(h, n, attrs.get(int(h, 16)))
                     for h, n in rows if attrs.get(int(h, 16)) != n]
            print("ResourceIndex fallback switch: %d cases, %d disagree"
                  % (len(rows), len(wrong)))
            for h, n, want in wrong:
                print("  %s: switch says %r, AOSP says %r" % (h, n, want))
            if wrong:
                raise SystemExit("fallback switch disagrees with AOSP")

    src = emit(attrs, branch, ag)
    if a.check:
        old = open(OUT).read() if os.path.exists(OUT) else ""
        if old == src:
            print("CHECK PASS: %s is up to date (%d attrs)" % (OUT, len(attrs)))
            return 0
        print("CHECK FAIL: %s differs from a fresh generation" % OUT)
        with tempfile.NamedTemporaryFile("w", suffix=".java", delete=False) as f:
            f.write(src); tmp = f.name
        subprocess.run(["diff", "-u", OUT, tmp])
        return 1
    open(OUT, "w").write(src)
    print("wrote %s (%d attrs, branch %s)" % (OUT, len(attrs), branch))
    return 0


if __name__ == "__main__":
    sys.exit(main())
