package android.security.keystore;

import java.io.ByteArrayOutputStream;
import java.math.BigInteger;
import java.security.InvalidAlgorithmParameterException;
import java.security.KeyPair;
import java.security.KeyPairGenerator;
import java.security.KeyPairGeneratorSpi;
import java.security.PrivateKey;
import java.security.PublicKey;
import java.security.SecureRandom;
import java.security.Signature;
import java.security.spec.AlgorithmParameterSpec;
import java.security.spec.ECGenParameterSpec;
import java.util.Date;

import javax.security.auth.x500.X500Principal;

/**
 * android.security.keystore.AndroidKeyStoreKeyPairGeneratorSpi -- the SPI behind
 * {@code KeyPairGenerator.getInstance("EC"|"RSA", "AndroidKeyStore")}.
 *
 * <p>WHY THIS EXISTS. We registered {@code KeyGenerator.AES} and
 * {@code KeyGenerator.HmacSHA256} for the AndroidKeyStore provider but no
 * KeyPairGenerator at all, so the standard way an app mints a device-bound
 * ASYMMETRIC key simply threw. Measured on Instagram:
 * {@code TokenBindingStoreManager: Error building KeyPair in Android KeyStore.
 * No fallback enabled}. The same call is how apps do token binding, key
 * agreement, request signing and biometric-gated keys, so the gap is generic.
 *
 * <p>Mirrors AOSP's
 * {@code frameworks/base/keystore/java/android/security/keystore2/AndroidKeyStoreKeyPairGeneratorSpi}
 * in the parts an app can observe:
 * <ul>
 *   <li>{@code initialize(int, SecureRandom)} throws -- an AndroidKeyStore
 *       generator MUST be told its alias, which only a KeyGenParameterSpec
 *       carries;</li>
 *   <li>{@code initialize(AlgorithmParameterSpec, SecureRandom)} requires a
 *       {@link KeyGenParameterSpec} with a non-null alias;</li>
 *   <li>{@code generateKeyPair()} generates the pair, mints a SELF-SIGNED X.509
 *       certificate for it, stores both under the alias, and returns the pair.
 *       The certificate matters: AOSP always creates one, and
 *       {@code KeyStore.getCertificate(alias).getPublicKey()} is how most
 *       callers get the public half back.</li>
 * </ul>
 *
 * <p>⚠ SCOPE, because this sits next to a line this project does not cross.
 * This is ordinary platform-API work: a REAL key pair, generated by the host's
 * JCA, stored in our keystore, with the self-signed certificate AOSP returns.
 * It is NOT key attestation. A key minted here honestly has no hardware
 * attestation chain, we do not fabricate one, and anything that demands a
 * Google-rooted attestation certificate will still fail -- as it should.
 *
 * <p>Storage remains software-backed. Authentication-bound private keys use
 * opaque API handles and the restricted cipher/signature routes, which require
 * actual native OS authorization; this is not hardware KeyMint enforcement.
 */
public abstract class AndroidKeyStoreKeyPairGeneratorSpi extends KeyPairGeneratorSpi {

    public static final class EC extends AndroidKeyStoreKeyPairGeneratorSpi {
        public EC() { super("EC", 256, "SHA256withECDSA"); }
        @Override AlgorithmParameterSpec sizeSpec(int bits) {
            // AOSP maps a keystore EC key size onto the matching NIST curve.
            switch (bits) {
                case 224: return new ECGenParameterSpec("secp224r1");
                case 256: return new ECGenParameterSpec("secp256r1");
                case 384: return new ECGenParameterSpec("secp384r1");
                case 521: return new ECGenParameterSpec("secp521r1");
                default:  return null;
            }
        }
    }

    public static final class RSA extends AndroidKeyStoreKeyPairGeneratorSpi {
        public RSA() { super("RSA", 2048, "SHA256withRSA"); }
        @Override AlgorithmParameterSpec sizeSpec(int bits) { return null; }
    }

    private final String algorithm;
    private final int defaultKeySizeBits;
    private final String signatureAlgorithm;

    private KeyGenParameterSpec spec;
    private SecureRandom random;
    private AndroidKeyStoreAuthPolicy policy = AndroidKeyStoreAuthPolicy.NONE;

    AndroidKeyStoreKeyPairGeneratorSpi(String algorithm, int defaultKeySizeBits,
                                       String signatureAlgorithm) {
        this.algorithm = algorithm;
        this.defaultKeySizeBits = defaultKeySizeBits;
        this.signatureAlgorithm = signatureAlgorithm;
    }

    /** Null when the size does not map to a named parameter set (RSA, where the
     *  size is passed to the generator directly). */
    abstract AlgorithmParameterSpec sizeSpec(int bits);

    @Override
    public void initialize(int keysize, SecureRandom random) {
        // AOSP wording.
        throw new IllegalArgumentException(
            "Cannot initialize without a " + KeyGenParameterSpec.class.getName()
            + " parameter");
    }

    @Override
    public void initialize(AlgorithmParameterSpec params, SecureRandom random)
            throws InvalidAlgorithmParameterException {
        this.spec = null;
        this.policy = AndroidKeyStoreAuthPolicy.NONE;
        if (!(params instanceof KeyGenParameterSpec)) {
            throw new InvalidAlgorithmParameterException(
                "Unsupported params class: "
                + (params == null ? "null" : params.getClass().getName())
                + ". Supported: " + KeyGenParameterSpec.class.getName());
        }
        KeyGenParameterSpec s = (KeyGenParameterSpec) params;
        if (s.getKeystoreAlias() == null) {
            throw new InvalidAlgorithmParameterException("KeyStore entry alias not provided");
        }
        if (s.isStrongBoxBacked()) throw new StrongBoxUnavailableException("This host has no StrongBox");
        if (s.isUserAuthenticationRequired() && s.getAttestationChallenge() != null)
            throw new InvalidAlgorithmParameterException("Host authentication keys cannot provide Android hardware attestation");
        policy = AndroidKeyStoreAuthPolicy.from(s, algorithm, s.getKeySize() == -1 ? defaultKeySizeBits : s.getKeySize());
        this.spec = s;
        this.random = random;
    }

    @Override
    public KeyPair generateKeyPair() {
        if (spec == null) {
            throw new IllegalStateException(
                "Not initialized with " + KeyGenParameterSpec.class.getName());
        }
        int bits = spec.getKeySize();
        if (bits == -1) bits = defaultKeySizeBits;

        final KeyPair pair;
        try {
            KeyPairGenerator g = KeyPairGenerator.getInstance(algorithm);
            AlgorithmParameterSpec named = sizeSpec(bits);
            SecureRandom rnd = (random != null) ? random : new SecureRandom();
            if (named != null) g.initialize(named, rnd);
            else               g.initialize(bits, rnd);
            pair = g.generateKeyPair();
        } catch (Exception e) {
            throw new IllegalStateException(
                "Failed to generate " + algorithm + " key pair", e);
        }

        try {
            byte[] cert = selfSign(pair, spec, signatureAlgorithm);
            MacApkKeyStoreBackend.get().putKeyPair(
                spec.getKeystoreAlias(), algorithm,
                pair.getPrivate().getEncoded(), cert, policy);
        } catch (Exception e) {
            throw new IllegalStateException(
                "Failed to store key pair for alias " + spec.getKeystoreAlias(), e);
        }
        return policy.required ? new KeyPair(pair.getPublic(), MacApkKeyStoreBackend.get().getPrivateKey(spec.getKeystoreAlias())) : pair;
    }

    // ---------------------------------------------------------------------
    // A minimal self-signed X.509 v3 certificate, written by hand.
    //
    // WHY BY HAND. AOSP always mints one of these for a generated keystore key
    // pair, so KeyStore.getCertificate(alias) must return something real. The
    // obvious tool would be BouncyCastle's certificate builder, but that lives
    // in bcpkix and we vendor only bcprov -- and bcprov 1.79 has dropped the old
    // X509V3CertificateGenerator. Writing the DER directly avoids adding a
    // dependency for ~120 lines of very mechanical encoding, and the one hard
    // part is free: publicKey.getEncoded() IS the SubjectPublicKeyInfo DER, so
    // it is embedded verbatim rather than re-encoded.
    // ---------------------------------------------------------------------

    private static byte[] selfSign(KeyPair pair, KeyGenParameterSpec spec,
                                   String sigAlg) throws Exception {
        X500Principal subject = spec.getCertificateSubject();
        if (subject == null) subject = new X500Principal("CN=Android Keystore Key");
        BigInteger serial = spec.getCertificateSerialNumber();
        if (serial == null) serial = BigInteger.ONE;
        Date notBefore = spec.getCertificateNotBefore();
        Date notAfter  = spec.getCertificateNotAfter();
        if (notBefore == null) notBefore = new Date();
        if (notAfter == null) {
            // AOSP's default is 2048-01-01; any long horizon works, and a fixed
            // one keeps the certificate stable across regeneration.
            notAfter = new Date(2461449600000L);
        }

        byte[] algId = sigAlgId(sigAlg);
        byte[] name  = subject.getEncoded();   // already DER Name

        ByteArrayOutputStream tbs = new ByteArrayOutputStream();
        // [0] EXPLICIT version, v3 == INTEGER 2
        tbs.write(tagged(0xA0, der(0x02, new byte[]{2})));
        tbs.write(der(0x02, unsignedInt(serial)));
        tbs.write(algId);
        tbs.write(name);                                    // issuer == subject
        ByteArrayOutputStream validity = new ByteArrayOutputStream();
        validity.write(time(notBefore));
        validity.write(time(notAfter));
        tbs.write(der(0x30, validity.toByteArray()));
        tbs.write(name);                                    // subject
        tbs.write(pair.getPublic().getEncoded());           // SubjectPublicKeyInfo
        byte[] tbsDer = der(0x30, tbs.toByteArray());

        final byte[] sigBytes;
        if (spec.isUserAuthenticationRequired()) {
            // Android documents an invalid certificate signature when the new
            // private key is not authorized to sign without authentication.
            // Do not perform a pre-auth signing operation merely to mint its
            // public-key container. This is not an attestation certificate.
            sigBytes = pair.getPrivate() instanceof java.security.interfaces.RSAKey rsa
                ? new byte[(rsa.getModulus().bitLength() + 7) / 8]
                : new byte[]{0x30, 0x06, 0x02, 0x01, 0, 0x02, 0x01, 0};
        } else {
            Signature sig = Signature.getInstance(sigAlg);
            sig.initSign(pair.getPrivate()); sig.update(tbsDer); sigBytes = sig.sign();
        }

        ByteArrayOutputStream cert = new ByteArrayOutputStream();
        cert.write(tbsDer);
        cert.write(algId);
        // BIT STRING with 0 unused bits.
        byte[] bits = new byte[sigBytes.length + 1];
        System.arraycopy(sigBytes, 0, bits, 1, sigBytes.length);
        cert.write(der(0x03, bits));
        return der(0x30, cert.toByteArray());
    }

    /** AlgorithmIdentifier. ECDSA-with-SHA256 omits the parameters field;
     *  sha256WithRSAEncryption requires an explicit NULL (RFC 4055 §2.1). */
    private static byte[] sigAlgId(String sigAlg) throws Exception {
        ByteArrayOutputStream b = new ByteArrayOutputStream();
        if ("SHA256withECDSA".equals(sigAlg)) {
            b.write(der(0x06, new byte[]{0x2A, (byte)0x86, 0x48, (byte)0xCE,
                                         0x3D, 0x04, 0x03, 0x02}));  // 1.2.840.10045.4.3.2
        } else {
            b.write(der(0x06, new byte[]{0x2A, (byte)0x86, 0x48, (byte)0x86,
                                         (byte)0xF7, 0x0D, 0x01, 0x01, 0x0B})); // 1.2.840.113549.1.1.11
            b.write(der(0x05, new byte[0]));   // NULL
        }
        return der(0x30, b.toByteArray());
    }

    /** UTCTime before 2050, GeneralizedTime from 2050 on (RFC 5280 §4.1.2.5). */
    private static byte[] time(Date d) throws Exception {
        java.text.SimpleDateFormat f;
        int tag;
        java.util.Calendar c = java.util.Calendar.getInstance(
            java.util.TimeZone.getTimeZone("UTC"));
        c.setTime(d);
        if (c.get(java.util.Calendar.YEAR) < 2050) {
            f = new java.text.SimpleDateFormat("yyMMddHHmmss'Z'");
            tag = 0x17;
        } else {
            f = new java.text.SimpleDateFormat("yyyyMMddHHmmss'Z'");
            tag = 0x18;
        }
        f.setTimeZone(java.util.TimeZone.getTimeZone("UTC"));
        return der(tag, f.format(d).getBytes("US-ASCII"));
    }

    /** Serial numbers are INTEGERs and must not look negative. */
    private static byte[] unsignedInt(BigInteger v) {
        byte[] b = v.abs().toByteArray();
        if (b.length == 0) return new byte[]{0};
        return b;   // BigInteger.toByteArray() is already two's complement, sign bit clear for abs()
    }

    private static byte[] tagged(int tag, byte[] content) throws Exception {
        return der(tag, content);
    }

    /** DER TLV with the long-form length encoding when needed. */
    private static byte[] der(int tag, byte[] content) throws Exception {
        ByteArrayOutputStream out = new ByteArrayOutputStream();
        out.write(tag);
        int n = content.length;
        if (n < 0x80) {
            out.write(n);
        } else {
            int bytes = (n < 0x100) ? 1 : (n < 0x10000) ? 2 : (n < 0x1000000) ? 3 : 4;
            out.write(0x80 | bytes);
            for (int i = bytes - 1; i >= 0; i--) out.write((n >>> (8 * i)) & 0xFF);
        }
        out.write(content);
        return out.toByteArray();
    }
}
