# ---- App icon -------------------------------------------------------
# Generate AppIcon.icns from the 512px master PNG so the launcher shows
# the Mac.apk icon in the Dock/Finder (CFBundleIconFile=AppIcon in
# Info.plist). The same master is copied next to the runtime binary as
# macapk_default_icon.png so a launched app that ships no icon of its own
# still gets the Mac.apk tile (the runtime resolves MACAPK_DEFAULT_ICON /
# exe-relative) instead of a blank Dock entry.
ICON_SRC="$PROJECT_DIR/images/mac_apk_icon_512.png"
if [ -f "$ICON_SRC" ]; then
    ICONSET_PARENT="$(mktemp -d)"
    ICONSET="$ICONSET_PARENT/AppIcon.iconset"
    mkdir -p "$ICONSET"
    # Standard macOS iconset sizes. Down-scales from the 512 master are
    # crisp; only the 1024 (512x512@2x) tile is an up-scale, acceptable
    # for the very largest Finder preview.
    for spec in "16:icon_16x16" "32:icon_16x16@2x" "32:icon_32x32" \
                "64:icon_32x32@2x" "128:icon_128x128" "256:icon_128x128@2x" \
                "256:icon_256x256" "512:icon_256x256@2x" "512:icon_512x512" \
                "1024:icon_512x512@2x"; do
        px="${spec%%:*}"; name="${spec##*:}"
        sips -z "$px" "$px" "$ICON_SRC" --out "$ICONSET/${name}.png" >/dev/null 2>&1 || true
    done
    if iconutil -c icns "$ICONSET" -o "$RESOURCES_DIR/AppIcon.icns" 2>/dev/null; then
        echo "  Bundled Resources/AppIcon.icns"
    else
        echo "  WARN: iconutil failed; launcher will use the generic icon."
    fi
    rm -rf "$ICONSET_PARENT"
    # Default Dock icon for launched apps that ship no icon of their own.
    cp "$ICON_SRC" "$RESOURCES_DIR/macapk_default_icon.png"
    echo "  Bundled Resources/macapk_default_icon.png"
else
    echo "  Note: $ICON_SRC not found; no custom app icon bundled."
fi

echo "[5/5] Setting bundle metadata..."
# PkgInfo file is legacy but some macOS tools still expect it.
printf "APPL????" > "$CONTENTS/PkgInfo"

