# Self-containment self-check: non-fatal (a build that succeeds but isn't
# fully self-contained is still a usable dev build), but printed loudly so
# a regression here is seen immediately rather than discovered later on
# someone else's clean Mac. See scripts/audit_bundle_deps.sh.
if [ -x "$SCRIPT_DIR/audit_bundle_deps.sh" ]; then
    echo ""
    AUDIT_OUT="$(mktemp -t macapk_bundle_audit)"
    if bash "$SCRIPT_DIR/audit_bundle_deps.sh" "$APP_DIR" > "$AUDIT_OUT" 2>&1; then
        echo "Self-containment audit: PASS (zero external Mach-O dependencies)"
    else
        echo "Self-containment audit: FAIL -- see external deps below"
        grep -E "EXTERNAL|^---" "$AUDIT_OUT" | grep -B1 EXTERNAL || true
    fi
    rm -f "$AUDIT_OUT"
