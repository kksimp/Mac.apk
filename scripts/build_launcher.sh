#!/usr/bin/env bash
# build_launcher.sh
#
# Builds the Mac.apk launcher app bundle directly with swiftc and the macOS
# command line tools. No Xcode project required, which means contributors can
# clone, run one script, and have a working .app.
#
# Output: build/Mac.apk.app
#
# Why no Xcode project: project files are huge, churn on every minor edit, and
# obscure the actual build steps. For an OS-layer free software project, having
# a transparent shell-script build is more friendly to contributors and to
# packagers downstream (homebrew, MacPorts, nixpkgs).

set -euo pipefail

# --promote installs the bundle this script builds over the ONE canonical
# Mac.apk.app, via scripts/promote_app.sh. WITHOUT it, the default path now
# WARNS when a canonical app exists, because "built" and "installed" are
# different things and this script only ever did the first -- see the block at
# the tail for the measurement that made the warning necessary.
PROMOTE=0
for a in "${@:-}"; do
    case "$a" in
        "")         ;;
        --promote)  PROMOTE=1 ;;
        *) echo "Unknown arg: $a (only --promote)" >&2; exit 2 ;;
    esac
done

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"
# INTERIM (retire when Xcode 27 is installed): fall back to an SDK the active
# linker can read (swiftc honours SDKROOT). One loud line when it acts.
. "$SCRIPT_DIR/sdk_fallback.sh"
LAUNCHER_DIR="$PROJECT_DIR/launcher"
RUNTIME_BIN="$PROJECT_DIR/runtime/build/bin/macapk-runtime"
BUILD_DIR="$PROJECT_DIR/build"
APP_DIR="$BUILD_DIR/Mac.apk.app"
CONTENTS="$APP_DIR/Contents"
MACOS_DIR="$CONTENTS/MacOS"
RESOURCES_DIR="$CONTENTS/Resources"

# --promote is an install, so it goes through scripts/install_guard.sh (2026-10-07):
# refuse up front, before compiling anything, when this tree lacks what is
# already installed (MACAPK_FORCE_INSTALL=1 overrides), and hold the
# machine-wide install lock across the promote + staging at the tail.
. "$SCRIPT_DIR/install_guard.sh"
if [ "$PROMOTE" -eq 1 ]; then
    ig_check_contains "$PROJECT_DIR" "${MACAPK_CANONICAL_APP:-/Applications/Mac.apk.app}" || exit 3
fi

# Confirm Apple toolchain.
if ! command -v swiftc >/dev/null; then
    echo "ERROR: swiftc not found. Install Xcode command line tools (xcode-select --install)." >&2
    exit 1
fi

# Clean rebuild. The launcher is small enough that incremental builds are
# unnecessary and create confusing stale-binary scenarios.
rm -rf "$APP_DIR"
mkdir -p "$MACOS_DIR" "$RESOURCES_DIR"

# Stamp this build with a timestamp + short git hash. The launcher header
# displays this, which is the easiest way to confirm a fresh build is
# actually running (otherwise Finder/Dock can launch a stale cached copy
# and you waste time chasing phantom bugs).
BUILD_STAMP="$(date '+%y%m%d.%H%M')"
GIT_HASH="$(git -C "$PROJECT_DIR" rev-parse --short HEAD 2>/dev/null || echo nogit)"
GIT_DIRTY=""
if ! git -C "$PROJECT_DIR" diff --quiet 2>/dev/null \
   || ! git -C "$PROJECT_DIR" diff --cached --quiet 2>/dev/null; then
    GIT_DIRTY="+dirty"
fi
BUILD_ID="${BUILD_STAMP}-${GIT_HASH}${GIT_DIRTY}"

# The release number the update check compares against GitHub Releases
# (launcher/UpdateCheck.swift). Only scripts/release.sh sets
# MACAPK_RELEASE_VERSION, from VERSION, so only the build we publish carries
# one; every other build bakes nil and never reports an update. Release tags on
# kksimp/Mac.apk-Releases are "v" + this number.
RELEASE_VERSION_SWIFT="nil"
if [ -n "${MACAPK_RELEASE_VERSION:-}" ]; then
    if ! printf '%s' "$MACAPK_RELEASE_VERSION" | grep -Eq '^[0-9]+(\.[0-9]+)*$'; then
        echo "ERROR: MACAPK_RELEASE_VERSION='$MACAPK_RELEASE_VERSION' is not a dotted version like 1.0.2016" >&2
        exit 1
    fi
    RELEASE_VERSION_SWIFT="\"$MACAPK_RELEASE_VERSION\""
    echo "  Release version: $MACAPK_RELEASE_VERSION (update check enabled)"
fi

BUILD_INFO_SWIFT="$LAUNCHER_DIR/BuildInfo.generated.swift"
cat > "$BUILD_INFO_SWIFT" <<EOF
// Auto-generated by scripts/build_launcher.sh. Do not edit.
enum BuildInfo {
    static let id = "$BUILD_ID"
    /// Set only for builds published to GitHub Releases (scripts/release.sh).
    static let releaseVersion: String? = $RELEASE_VERSION_SWIFT
}
EOF
echo "  Build ID: $BUILD_ID"

echo "[1/5] Compiling launcher Swift sources..."

# Target macOS 26. The project verifies against macOS 26 (Tahoe) on Apple
# Silicon only, and Info.plist declares LSMinimumSystemVersion 26.4 (the x18 entitlement floor), so a
# lower swiftc target would only mean the two disagree: the binary would
# claim to run somewhere the bundle refuses to launch. It also gates the
# current NSWorkspace.setDefaultApplication(at:toOpen:completionHandler:)
# used for .apk handler registration, whose LaunchServices C predecessor
# is API_DEPRECATED and banned here.
SWIFT_TARGET="arm64-apple-macos26.0"

swiftc \
    -O \
    -parse-as-library \
    -target "$SWIFT_TARGET" \
    -framework AppKit \
    -framework SwiftUI \
    -framework UniformTypeIdentifiers \
    -framework Combine \
    -o "$MACOS_DIR/MacApk" \
    "$LAUNCHER_DIR/MacApkLauncherApp.swift" \
    "$LAUNCHER_DIR/InstallCore.swift" \
    "$LAUNCHER_DIR/BundleGenerator.swift" \
    "$LAUNCHER_DIR/UpdateCheck.swift" \
    "$BUILD_INFO_SWIFT"

# The per-app stub template. Each installed APK gets a generated .app whose
# executable is a COPY of this binary; the stub resolves the one shared
# Mac.apk and execv's its runtime, so the runtime is never copied per app.
#
# It is signed HERE, once, as a STANDALONE FILE -- never inside a bundle.
# That is load-bearing, and the obvious alternative does not work: running
# codesign against a path inside a .app makes codesign detect the enclosing
# bundle and write Contents/_CodeSignature with a resource seal, after which
# the first byte the app writes under Contents/android/ invalidates it
# ("a sealed resource is missing or invalid", measured 2026-08-10). An
# ad-hoc signature embedded in a standalone Mach-O stays valid wherever the
# file is later copied, so generated bundles carry no seal at all and there
# is nothing for app data to break. Generated bundles are NEVER codesigned.
#
# AppStubMain.swift cannot compile alone: it calls RegistryStore from
# InstallCore.swift. It must NOT join the launcher link line above either,
# because two @main types in one binary do not link.
echo "[2/5] Compiling per-app stub template..."
mkdir -p "$RESOURCES_DIR/appstub"
swiftc \
    -O \
    -parse-as-library \
    -target "$SWIFT_TARGET" \
    -framework AppKit \
    -o "$RESOURCES_DIR/appstub/MacApkAppStub" \
    "$LAUNCHER_DIR/AppStubMain.swift" \
    "$LAUNCHER_DIR/InstallCore.swift"
codesign --force --sign - --identifier org.macapk.appstub \
    "$RESOURCES_DIR/appstub/MacApkAppStub"

# macapk-installhelper: a SYNCHRONOUS, headless install.
#
# It exists because `open --env` cannot deliver an environment to an app that
# is ALREADY RUNNING -- macOS answers "was already running and so the
# additional environment variables could not be set". The harness's
# MACAPK_INSTALL_NOUI therefore never arrived, the Finder path raised its
# confirm dialog, and an unattended run blocked until timeout and reported "no
# bundle in 300s" -- which reads as an install failure and is really "nobody
# clicked". Measured 2026-08-11.
#
# Lives in Contents/bin (next to the translator) rather than Resources, because
# it resolves the runtime relative to its own path.
echo "[3/5] Compiling macapk-installhelper..."
mkdir -p "$CONTENTS/bin"
swiftc \
    -O \
    -parse-as-library \
    -target "$SWIFT_TARGET" \
    -framework AppKit \
    -o "$CONTENTS/bin/macapk-installhelper" \
    "$LAUNCHER_DIR/InstallHelperMain.swift" \
    "$LAUNCHER_DIR/InstallCore.swift" \
    "$LAUNCHER_DIR/BundleGenerator.swift" \
    "$BUILD_INFO_SWIFT"

# "Mac.apk Location": the helper app that holds CLLocationManager for every
# app's runtime (launcher/LocationHelperMain.swift has the why: macOS shows
# its location prompt only to a process that IS a bundle's executable, and
# the runtime is not one). It must be a real .app with its own Info.plist
# (usage string, LSUIElement), signed with the hardened runtime and the
# location entitlement, or TCC refuses it without a prompt. Signed as a
# BUNDLE: nothing ever writes inside it, so the seal stays valid.
echo "[3b/5] Building the Mac.apk Location helper app..."
LOC_APP="$CONTENTS/Helpers/Mac.apk Location.app"
rm -rf "$LOC_APP"
mkdir -p "$LOC_APP/Contents/MacOS"
swiftc \
    -O \
    -parse-as-library \
    -target "$SWIFT_TARGET" \
    -framework CoreLocation \
    -o "$LOC_APP/Contents/MacOS/macapk-location" \
    "$LAUNCHER_DIR/LocationHelperMain.swift"
cat > "$LOC_APP/Contents/Info.plist" <<'LOCPLIST'
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>CFBundleIdentifier</key><string>org.macapk.location</string>
    <key>CFBundleName</key><string>Mac.apk Location</string>
    <key>CFBundleDisplayName</key><string>Mac.apk Location</string>
    <key>CFBundleExecutable</key><string>macapk-location</string>
    <key>CFBundlePackageType</key><string>APPL</string>
    <key>CFBundleInfoDictionaryVersion</key><string>6.0</string>
    <key>CFBundleShortVersionString</key><string>1.0</string>
    <key>CFBundleVersion</key><string>1</string>
    <key>LSMinimumSystemVersion</key><string>26.4</string>
    <key>LSUIElement</key><true/>
    <key>NSLocationWhenInUseUsageDescription</key><string>Android apps running in Mac.apk use your location through this. Each app also asks you separately, and only the apps you allow get it.</string>
    <key>NSLocationUsageDescription</key><string>Android apps running in Mac.apk use your location through this. Each app also asks you separately, and only the apps you allow get it.</string>
</dict>
</plist>
LOCPLIST
# The ONE entitlements file (runtime/scripts/jit-entitlements.plist; see its
# header and debug/entitlements_check.sh): it carries
# com.apple.security.personal-information.location since v1.0.1712.
codesign --force --sign - --options runtime \
    --entitlements "$PROJECT_DIR/runtime/scripts/jit-entitlements.plist" \
    --identifier org.macapk.location "$LOC_APP"

echo "[4/5] Copying Info.plist and bundling runtime binary..."
cp "$LAUNCHER_DIR/Info.plist" "$CONTENTS/Info.plist"

# STRICT plist validation. `plutil -lint` is NOT sufficient: it accepts a double
# hyphen inside an XML comment, which illegally terminates the comment and which
# strict parsers reject. That is not hypothetical -- a comment added to
# Info.plist on 2026-08-21 shipped malformed and `plutil -lint` reported OK, the
# same lenient-vs-strict split that broke codesign via jit-entitlements.plist the
# same night. Python's expat is strict, so use it as the gate.
if ! /usr/bin/env python3 - "$CONTENTS/Info.plist" <<'PYPLIST'
import plistlib, re, sys, io
path = sys.argv[1]
try:
    plistlib.load(open(path, "rb"))
except Exception as e:
    print(f"[build] FATAL: {path} is not well-formed XML: {e}", file=sys.stderr)
    raise SystemExit(1)
src = io.open(path, encoding="utf-8").read()
bad = [c for c in re.findall(r"<!--.*?-->", src, re.S) if "--" in c[4:-3]]
if bad:
    print(f"[build] FATAL: {path} has {len(bad)} XML comment(s) containing a double",
          file=sys.stderr)
    print("[build]        hyphen, which terminates the comment early. plutil accepts", file=sys.stderr)
    print("[build]        this; strict parsers do not. First offender:", file=sys.stderr)
    print("[build]        " + bad[0][:160].replace("\n", " "), file=sys.stderr)
    raise SystemExit(1)
PYPLIST
then
    echo "[build] Info.plist failed strict validation (see above)." >&2
    exit 1
fi

# Stamp the repo VERSION into the bundle. Until v1.0.1023 the plist carried
# hardcoded CFBundleShortVersionString=0.2.0 and CFBundleVersion=0.3.0 -- two
# different values, neither of which had matched reality for ~1000 versions. An
# alpha tester's bug report would have named a build that does not exist, and
# "which version are you running" is the first question of every triage.
#
# Both keys get the same value on purpose: our VERSION is already monotonic in
# its patch component (the VERSION-bumping rule in CLAUDE.md), which is what
# CFBundleVersion needs, and it is also what a human should quote, which is what
# CFBundleShortVersionString is for. We are not shipping to the App Store, whose
# stricter monotonicity rules are the only reason to keep the two apart.
#
# NOTE: per-app bundles (launcher/BundleGenerator.swift) deliberately do NOT get
# this -- their version keys describe the ANDROID app they wrap, not Mac.apk.
if [ -f "$PROJECT_DIR/VERSION" ]; then
    MACAPK_VER="$(tr -d '[:space:]' < "$PROJECT_DIR/VERSION")"
    if [ -n "$MACAPK_VER" ]; then
        /usr/libexec/PlistBuddy -c "Set :CFBundleShortVersionString $MACAPK_VER" \
            "$CONTENTS/Info.plist" >/dev/null 2>&1 || \
          /usr/libexec/PlistBuddy -c "Add :CFBundleShortVersionString string $MACAPK_VER" \
            "$CONTENTS/Info.plist" >/dev/null 2>&1
        /usr/libexec/PlistBuddy -c "Set :CFBundleVersion $MACAPK_VER" \
            "$CONTENTS/Info.plist" >/dev/null 2>&1 || \
          /usr/libexec/PlistBuddy -c "Add :CFBundleVersion string $MACAPK_VER" \
            "$CONTENTS/Info.plist" >/dev/null 2>&1
        echo "  Stamped version $MACAPK_VER into Info.plist"
    fi
else
    echo "  WARN: no $PROJECT_DIR/VERSION; bundle keeps the plist's placeholder version" >&2
fi

# Bundle the runtime binary into the .app if it has been built. The
# launcher's runtimePath() resolves the bundled binary first; if it's
# missing it falls back to ../runtime/build/bin/macapk-runtime.
#
# The bundle has to mirror the dev tree's `runtime/build/` layout because
# two pieces of code probe relative to two different anchors:
#
# (1) Runtime C++ side resolves paths relative to its own binary:
#     - ./libGLESv2.dylib, ./libEGL.dylib            @rpath @executable_path
#     - ./libmacapk-bionic-shim.dylib OR
#       ../bin/libmacapk-bionic-shim.dylib         dlopen'd by main.cpp
#     - ../lib/android-framework.jar                 config.h:kFrameworkJarRel
#     - ../lib/macapk-loader.jar                   config.h:kLoaderJarRel
#
# (2) Java loader (Boot.java) resolves paths relative to the loader-jar's
#     grandparent dir. In the bundle the loader jar lives at
#     Contents/lib/macapk-loader.jar, so its grandparent is Contents/.
#     Boot.java then probes:
#     - {bin,lib,native}/libmacapk-app-stub.dylib  locateStubLibrary()
#     - bin/macapk-translator                      locateTranslatorBinary()
#
# (3) AppClassLoader passes the translator's own dir as --shim-dir when
#     it runs the translator subprocess, so the bionic shim MUST live
#     next to macapk-translator (clang resolves -lmacapk-bionic-shim
#     against that directory at link time).
#
# So the layout is:
#   Resources/                runtime binary + ANGLE
#   bin/                      translator binary + bionic shim
#   lib/                      app-stub dylib + jars
BIN_DIR="$CONTENTS/bin"
LIB_DIR="$CONTENTS/lib"
if [ -x "$RUNTIME_BIN" ]; then
    mkdir -p "$BIN_DIR" "$LIB_DIR"
    cp "$RUNTIME_BIN" "$RESOURCES_DIR/macapk-runtime"
    chmod +x "$RESOURCES_DIR/macapk-runtime"
    echo "  Bundled Resources/macapk-runtime: $(du -h "$RESOURCES_DIR/macapk-runtime" | cut -f1)"

    RUNTIME_BIN_DIR="$(dirname "$RUNTIME_BIN")"
    RUNTIME_LIB_DIR="$PROJECT_DIR/runtime/build/lib"

    # ANGLE: next to the runtime binary in Resources/, found at
    # @executable_path rpath baked into the runtime binary.
    #   libGLESv2/libEGL  the GLES/EGL front end (Metal + Vulkan backends)
    #   libvulkan         ANGLE's bundled Vulkan-Loader (only present on a
    #                     Vulkan-enabled build; the front end links it)
    #   libMoltenVK       the Vulkan ICD (Vulkan-over-Metal); the loader
    #                     dlopens it via MoltenVK_icd.json (see below).
    # The last two are optional so a Metal-only ANGLE build still bundles.
    for libname in libGLESv2.dylib libEGL.dylib libvulkan.dylib libMoltenVK.dylib libskiko-macos-arm64.dylib libmacapk-skia-metal.dylib; do
        if [ -f "$RUNTIME_BIN_DIR/$libname" ]; then
            cp "$RUNTIME_BIN_DIR/$libname" "$RESOURCES_DIR/$libname"
            echo "  Bundled Resources/$libname: $(du -h "$RESOURCES_DIR/$libname" | cut -f1)"
        fi
    done
    # MoltenVK ICD manifest: the runtime sets VK_ICD_FILENAMES to this path
    # (in Resources/, next to libMoltenVK.dylib) when MACAPK_ANGLE_BACKEND=vulkan.
    if [ -f "$RUNTIME_BIN_DIR/MoltenVK_icd.json" ]; then
        cp "$RUNTIME_BIN_DIR/MoltenVK_icd.json" "$RESOURCES_DIR/MoltenVK_icd.json"
        echo "  Bundled Resources/MoltenVK_icd.json"
    fi

    # Translator + bionic shim go to Contents/bin/. The translator
    # subprocess is launched with --shim-dir Contents/bin/, so the shim
    # has to live next to the translator binary for clang's
    # -lmacapk-bionic-shim to resolve. The runtime's main.cpp probes
    # both ./shim and ../bin/shim so it finds this path too.
    # Translator is optional: skipped silently if Capstone wasn't
    # installed at runtime build time; APKs with ARM32 native libs will
    # then fail at System.loadLibrary instead of at bundle time.
    if [ -f "$RUNTIME_BIN_DIR/macapk-translator" ]; then
        cp "$RUNTIME_BIN_DIR/macapk-translator" "$BIN_DIR/macapk-translator"
        chmod +x "$BIN_DIR/macapk-translator"
        echo "  Bundled bin/macapk-translator: $(du -h "$BIN_DIR/macapk-translator" | cut -f1)"
    fi
    if [ -f "$RUNTIME_BIN_DIR/libmacapk-bionic-shim.dylib" ]; then
        cp "$RUNTIME_BIN_DIR/libmacapk-bionic-shim.dylib" \
            "$BIN_DIR/libmacapk-bionic-shim.dylib"
        echo "  Bundled bin/libmacapk-bionic-shim.dylib: $(du -h "$BIN_DIR/libmacapk-bionic-shim.dylib" | cut -f1)"
    fi

    # App-stub dylib + jars under Contents/lib/. The stub is what
    # AppClassLoader.findLibrary returns so APK <clinit>s that call
    # System.loadLibrary survive. Boot.java probes lib/ here.
    if [ -f "$RUNTIME_BIN_DIR/libmacapk-app-stub.dylib" ]; then
        cp "$RUNTIME_BIN_DIR/libmacapk-app-stub.dylib" \
            "$LIB_DIR/libmacapk-app-stub.dylib"
        echo "  Bundled lib/libmacapk-app-stub.dylib: $(du -h "$LIB_DIR/libmacapk-app-stub.dylib" | cut -f1)"
    fi
    for jar in android-framework.jar macapk-loader.jar; do
        if [ -f "$RUNTIME_LIB_DIR/$jar" ]; then
            cp "$RUNTIME_LIB_DIR/$jar" "$LIB_DIR/$jar"
            echo "  Bundled lib/$jar: $(du -h "$LIB_DIR/$jar" | cut -f1)"
        else
            echo "  WARN: $jar not found at $RUNTIME_LIB_DIR. Runtime will fail to boot."
        fi
    done

    # --patch-module dirs (runtime/scripts/build.sh compiles them; main.cpp
    # passes --patch-module=<module>=<Contents/lib/<dir>> when the dir exists).
    # These are DIRECTORIES of .class files, not jars, so they need their own
    # copy step.
    #
    # ⚠ These were never bundled before 2026-08-12, which meant the java.base
    # patch (java.text.SimpleDateFormat's standalone-day-of-week 'c', added
    # v1.0.845, docs/jetfix_2026-07-31.md) was live when running the repo's
    # runtime/build/bin/macapk-runtime directly and SILENTLY ABSENT in every
    # bundled app the owner actually launches -- main.cpp's fs::exists() guard
    # makes that failure completely quiet. Any measurement taken through the
    # dev binary therefore tested different bytecode from the .app. Copying the
    # dirs is the whole fix.
    for pdir in java_base_patch jdk_unsupported_patch; do
        if [ -d "$RUNTIME_LIB_DIR/$pdir" ]; then
            rm -rf "$LIB_DIR/$pdir"
            cp -R "$RUNTIME_LIB_DIR/$pdir" "$LIB_DIR/$pdir"
            echo "  Bundled lib/$pdir/: $(find "$LIB_DIR/$pdir" -name '*.class' | wc -l | tr -d ' ') class(es)"
        fi
    done

    # Pairip boot refs (v1.0.1573): the harvested per-image refs that main.cpp defaults
    # MACAPK_PAIRIP_{IMPORT_TABLE,INJECT_STRINGS,CODE_PATCH_DIR} to (it looks at
    # <bin>/../lib/pairip-refs, i.e. Contents/lib/pairip-refs). Bundling them makes
    # Play-Minecraft boot + render + reach Xbox sign-in from the INSTALLED .app with no env
    # flags. Every application is gated on structural pairip detection + a soname match, and
    # the raw-.text code patch on a per-build .fnv byte-check, so no other app is touched.
    # Same dev-binary-vs-bundle-parity reason as the patch-module dirs above.
    if [ -d "$RUNTIME_LIB_DIR/pairip-refs" ]; then
        rm -rf "$LIB_DIR/pairip-refs"
        cp -R "$RUNTIME_LIB_DIR/pairip-refs" "$LIB_DIR/pairip-refs"
        echo "  Bundled lib/pairip-refs/: $(du -sh "$LIB_DIR/pairip-refs" | cut -f1)"
    fi

    # The build identity (JAVA_ID / NATIVE_ID, emitted by
    # runtime/scripts/build.sh). Cached per-app artifacts record the identity
    # of the code that produced them, so a converter, framework-jar,
    # translator or shim change regenerates them instead of being silently
    # reused. Without this file inside the bundle the GUI cannot tell whether
    # what it is about to run matches what produced the caches, which is the
    # exact failure this whole mechanism exists to remove.
    if [ -f "$PROJECT_DIR/runtime/build/build-id.txt" ]; then
        # Resources/build-id.txt, NOT Contents/build-id.txt: a plain file loose in
        # Contents/ cannot be sealed, and `codesign --verify --deep --strict` fails
        # with "code object is not signed at all / In subcomponent: .../build-id.txt".
        # That blocked the first real DMG build (v1.0.1019) and had been latent since
        # the file was introduced, because nothing ever ran that verify -- build_dist.sh
        # swallowed its failure with `|| echo`. Contents/bin and Contents/lib are fine:
        # they hold Mach-O that gets signed individually.
        cp "$PROJECT_DIR/runtime/build/build-id.txt" "$CONTENTS/Resources/build-id.txt"
        echo "  Bundled build-id.txt: $(tr '\n' ' ' < "$CONTENTS/Resources/build-id.txt")"
    else
        echo "  WARN: runtime/build/build-id.txt missing. Freshness checking is"
        echo "        disabled for this bundle. Run runtime/scripts/build.sh."
    fi

    # macapk-elfexec sits next to the translator in the dev tree but was
    # never bundled, so a bundle-launched run could not reach it at all.
    if [ -f "$RUNTIME_BIN_DIR/macapk-elfexec" ]; then
        cp "$RUNTIME_BIN_DIR/macapk-elfexec" "$BIN_DIR/macapk-elfexec"
        chmod +x "$BIN_DIR/macapk-elfexec"
        echo "  Bundled bin/macapk-elfexec: $(du -h "$BIN_DIR/macapk-elfexec" | cut -f1)"
    fi
    # Vendored BouncyCastle provider jar (see main.cpp bcprov_jar / Boot.java).
    # Optional: absent just means BC-named crypto stays unavailable in the .app.
    for jar in bcprov-jdk18on-1.79.jar; do
        if [ -f "$RUNTIME_LIB_DIR/$jar" ]; then
            cp "$RUNTIME_LIB_DIR/$jar" "$LIB_DIR/$jar"
            echo "  Bundled lib/$jar: $(du -h "$LIB_DIR/$jar" | cut -f1)"
        fi
    done

    # ---- Self-containment staging (added 2026-08-14) -------------------
    #
    # Everything above copies OUR OWN build artifacts into the bundle, but
    # until this point macapk-runtime, macapk-translator and
    # libmacapk-bionic-shim.dylib still link against Homebrew (absolute
    # /opt/homebrew/... paths), and nothing bundles a `java` for the
    # install-time DEX converter JVM. A process launched from the Dock does
    # NOT inherit a login shell's PATH -- launchd hands GUI apps
    # /usr/bin:/bin:/usr/sbin:/sbin, not /opt/homebrew/bin -- so every one of
    # those gaps is invisible from a developer's terminal and breaks for
    # every real user. Measured 2026-08-14 on three Dock-launched apps
    # (Aurora Store, OpenCalculator, Vector Pinball): the then-bundled
    # apktool silently failed to run, so resource decode never happened, so
    # every layout inflate threw Resources$NotFoundException. (apktool is
    # gone since v1.0.1590 -- resources are read from the installed apk --
    # but the platform resource apk staged below is the same kind of
    # self-containment requirement.) See runtime/src/apk_unpacker.cpp's
    # ResolveJavaBin header comment.
    #
    # Order matters: the JRE has to exist before relink_bundle_deps.sh runs
    # (it points macapk-runtime's libjvm/libjli references at
    # Resources/jre/lib/...); the platform apk's own path doesn't interact
    # with either, so it can run any time in between.
    # The JDK is the ONE setting (MACAPK_JDK; debug/jdk25_select.sh), the same resolver
    # runtime/scripts/build.sh linked the runtime with, so the bundled JRE cannot be a
    # different feature from the libjvm the runtime expects (stage_jre.sh refuses a
    # mismatch). MACAPK_JDK unset = the legacy answer, byte for byte: an exported
    # JAVA_HOME, else brew's opt/openjdk@21.
    # shellcheck source=/dev/null
    . "$PROJECT_DIR/debug/jdk25_select.sh"
    JAVA_HOME_FOR_JRE="$(macapk_jdk_home)" || {
        echo "ERROR: no JDK for MACAPK_JDK=$(macapk_jdk_selected) (debug/jdk25_select.sh --candidates)" >&2
        exit 1
    }
    echo "  Staging self-contained JRE (jlink from $JAVA_HOME_FOR_JRE)..."
    bash "$SCRIPT_DIR/stage_jre.sh" "$JAVA_HOME_FOR_JRE" "$RESOURCES_DIR/jre"

    echo "  Staging the platform resource apk..."
    bash "$SCRIPT_DIR/stage_framework_res.sh" "$RESOURCES_DIR/tools"
    # v1.0.1590: apktool.jar is no longer bundled (nothing runs it); drop a
    # copy left by an older staging of this same bundle dir.
    rm -rf "$RESOURCES_DIR/tools/apktool"

    # Third-party licence notices for the components this bundle ships (the
    # redistribution obligation the DMG carries). Read from each component's
    # own licence text at build time so it is the text of the version shipped.
    echo "  Generating third-party notices..."
    bash "$SCRIPT_DIR/gen_third_party_notices.sh" "$RESOURCES_DIR/THIRD_PARTY_NOTICES.txt"

    echo "  Relinking Homebrew-linked binaries to @rpath..."
    bash "$SCRIPT_DIR/relink_bundle_deps.sh" "$CONTENTS" "$PROJECT_DIR"
else
    echo "  Note: runtime not built yet at $RUNTIME_BIN. Build it with runtime/scripts/build.sh."
    echo "  The launcher will fall back to the dev-tree path until you do."
fi

