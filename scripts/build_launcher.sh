# ---- promote, or say loudly that you did not ------------------------------
#
# WHY THIS EXISTS (measured 2026-08-19). scripts/rebuild_and_run.sh was the ONLY
# programmatic caller of this script in the whole repo, and CLAUDE.md's own
# "Or step by step:" recipe tells the reader to run
#     runtime/scripts/build.sh && scripts/build_launcher.sh && open build/Mac.apk.app
# -- a sequence that never promotes. So /Applications/Mac.apk.app keeps serving
# the PREVIOUSLY promoted GUI, install helper and app-stub template while the
# developer looks at a different bundle, and nothing anywhere says so. On this
# machine at the time of writing, the canonical app's MacApk and
# macapk-installhelper both carried build 260819.0937 while this script's last
# run had produced 260819.0956.
#
# The warning names BOTH ids on purpose: "you did not promote" is only
# actionable once you can see that the two builds actually differ.
CANONICAL="${MACAPK_CANONICAL_APP:-/Applications/Mac.apk.app}"
_embedded_id() {  # the BuildInfo stamp linked into a Swift binary, or empty
    strings -a "$1" 2>/dev/null \
        | grep -oE '^[0-9]{6}\.[0-9]{4}-[0-9a-f]{7,}(\+dirty)?$' | sort -u | head -n 1
}

if [ "$PROMOTE" -eq 1 ]; then
    echo ""
    if [ -x "$SCRIPT_DIR/promote_app.sh" ]; then
        IG_TREE="$PROJECT_DIR" ig_lock_acquire "build_launcher.sh --promote + stage" || exit 75
        trap 'ig_lock_release' EXIT
        MACAPK_INSTALL_VIA="build_launcher.sh --promote" "$SCRIPT_DIR/promote_app.sh" "$APP_DIR"
        # STAGE THE SHARED RUNTIME TOO. Promoting without this leaves the
        # canonical app fresh while every INSTALLED app keeps executing the
        # previous build, because an app's Contents/MacOS/<exec> symlinks into
        # ~/Library/Application Support/Mac.apk/runtime, not into this bundle.
        # That split was hit twice on 2026-08-19: staleness.sh reported it
        # correctly both times and nothing acted on it, which is how "newest
        # version always wins" quietly stops being true. Same one
        # implementation scripts/rebuild_and_run.sh calls.
        #
        # Nonzero here fails the build on purpose: a promote that could not
        # stage is NOT a successful promote, and a harness chaining off this
        # script must stop rather than measure old code.
        if ! "$SCRIPT_DIR/stage_shared_runtime.sh" "$CANONICAL"; then
            echo "" >&2
            echo "ERROR: promoted $CANONICAL but the SHARED RUNTIME was NOT staged" >&2
            echo "       (details above). Installed apps still execute the previous" >&2
            echo "       build. Exiting nonzero on purpose." >&2
            exit 1
        fi
    else
        echo "ERROR: --promote was requested but $SCRIPT_DIR/promote_app.sh is missing." >&2
        echo "       $APP_DIR was built but NOT installed; $CANONICAL is unchanged." >&2
        exit 1
    fi
elif [ "${MACAPK_NO_BUNDLE_SYNC:-0}" = "1" ]; then
    # scripts/rebuild_and_run.sh sets this and promotes immediately afterwards,
    # so warning there would be noise about something already handled.
    echo "Run with: open $APP_DIR"
elif [ -d "$CANONICAL" ]; then
    CANON_ID="$(_embedded_id "$CANONICAL/Contents/MacOS/MacApk")"
    echo ""
    echo "⚠ NOT PROMOTED. $CANONICAL still runs build ${CANON_ID:-unknown};"
    echo "  this build is $BUILD_ID."
    if [ -n "$CANON_ID" ] && [ "$CANON_ID" = "$BUILD_ID" ]; then
        echo "  (Those are the same id, so nothing is stale -- but the canonical app"
        echo "   was still not replaced by THIS bundle.)"
    fi
    echo "  Everything launched from the Dock, every installed app's stub, and every"
    echo "  headless install (Contents/bin/macapk-installhelper) keeps using the OLD"
    echo "  binaries until you promote. Next command:"
    echo "      scripts/build_launcher.sh --promote     # install this bundle"
    echo "      scripts/rebuild_and_run.sh              # full rebuild + promote + stage"
    echo "  To look at THIS bundle without installing it: open $APP_DIR"
else
    echo "Run with: open $APP_DIR"
    echo "(No canonical app at $CANONICAL yet; scripts/rebuild_and_run.sh installs one.)"
fi
